from .claude_closed_loop_protocol import RECEIPT_MARKER, TASK_MARKER, TASK_PROFILE, _block

ACCEPT_MARKER = "<!-- claude-loop-accept v1"
REFUSE_MARKER = "<!-- claude-loop-refuse v1"
CHECKPOINT_MARKER = "<!-- claude-loop-checkpoint v1"
ACCEPT_PROFILE = "CLAUDE_LOOP_ACCEPT_V1"
REFUSE_PROFILE = "CLAUDE_LOOP_REFUSE_V1"
CHECKPOINT_PROFILE = "CLAUDE_LOOP_CHECKPOINT_V1"
POLICY_PROFILE = "CLAUDE_LOOP_POLICY_V1"
FOOTER = "\n---\n_Generated by [Claude Code](https://claude.ai/code)_\n"

# request / task states
NEW, INVALID, REFUSED, WORKING, REVIEW_PENDING, CORRECTION, PASS, BLOCKED, UNREADABLE, CLOSED = (
    "NEW", "INVALID", "REFUSED", "WORKING", "REVIEW_PENDING", "CORRECTION", "PASS", "BLOCKED", "RECORD_UNREADABLE",
    "CLOSED")
IN_FLIGHT = {WORKING, REVIEW_PENDING, CORRECTION}
# worker actions
START, CORRECT, WAIT, IDLE, STOPPED = "START", "CORRECT", "WAIT", "IDLE", "STOPPED"

_KEY = re.compile(r"^\s*(goal|allowed_paths|acceptance|test_commands|mode)\s*:\s*(.*)$", re.I)
_PATH_OP = re.compile(r"`?([^\s`(),]+)`?\s*\(\s*(ADD|MODIFY|DELETE|RENAME)\s*\)", re.I)
_SIGNED = re.compile(r"^\s*(AI-Agent:\s*\S+|Generated (by|with) \[?Claude Code)", re.M)
_SHA40 = re.compile(r"^[0-9a-f]{40}$")


class PolicyError(ValueError):
    """The policy file is not a valid CLAUDE_LOOP_POLICY_V1."""


def _ts(text: str) -> datetime:
    return datetime.strptime(text, "%Y-%m-%dT%H:%M:%SZ").replace(tzinfo=timezone.utc)


def _fmt(when: datetime) -> str:
    return when.astimezone(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


# ------------------------------------------------------------------------------------------------ policy
_POLICY_KEYS = {"profile", "repository", "base_branch", "loop_id", "lane_id", "title_prefix", "branch_prefix",
                "trusted_writers", "record_apps", "control_issue", "expires_at", "max_new_tasks_per_day", "max_files",
                "max_corrective_rounds", "stall_minutes", "heartbeat_hours", "full_suite", "forbidden"}
_FORBIDDEN_KEYS = {"prefixes", "exact", "name_globs", "substrings", "existing_tests_read_only"}


def load_policy(data: Any) -> dict[str, Any]:
    """Validate a policy object (the parsed docs/claude-loop/active/policy.json); raise PolicyError if invalid."""
    if not isinstance(data, dict) or set(data) - {"note"} != _POLICY_KEYS:
        raise PolicyError("policy keys mismatch")
    if data["profile"] != POLICY_PROFILE:
        raise PolicyError("unsupported policy profile")
    for key in ("repository", "base_branch", "loop_id", "lane_id", "title_prefix", "branch_prefix"):
        if not isinstance(data[key], str) or not data[key]:
            raise PolicyError(f"policy {key} missing")
    if not data["branch_prefix"].startswith("claude/"):
        raise PolicyError("branch_prefix must start with claude/")
    for key in ("trusted_writers", "record_apps"):
        if not isinstance(data[key], list) or not data[key] or not all(isinstance(x, str) and x for x in data[key]):
            raise PolicyError(f"{key} missing")
    for key in ("control_issue", "max_new_tasks_per_day", "max_files", "max_corrective_rounds", "stall_minutes",
                "heartbeat_hours"):
        if isinstance(data[key], bool) or not isinstance(data[key], int) or data[key] < (0 if key ==
                                                                                       "max_corrective_rounds" else 1):
            raise PolicyError(f"policy {key} must be a positive integer")
    try:
        _ts(data["expires_at"])
    except (TypeError, ValueError) as exc:
        raise PolicyError("expires_at must be YYYY-MM-DDTHH:MM:SSZ") from exc
    if not isinstance(data["full_suite"], list) or not all(isinstance(c, str) and c for c in data["full_suite"]):
        raise PolicyError("full_suite must be a list of commands")
    forb = data["forbidden"]
    if not isinstance(forb, dict) or set(forb) != _FORBIDDEN_KEYS or forb["existing_tests_read_only"] is not True:
        raise PolicyError("forbidden keys mismatch (existing_tests_read_only must be true)")
    for key in _FORBIDDEN_KEYS - {"existing_tests_read_only"}:
        if not isinstance(forb[key], list) or not all(isinstance(x, str) and x for x in forb[key]):
            raise PolicyError(f"forbidden.{key} must be a list of strings")
    return data


# ------------------------------------------------------------------------------------------------ requests
def parse_request(body: str) -> tuple[dict[str, Any], list[str]]:
    """The request block of an issue body as fields, plus every problem found.  The body is data, never orders."""
    fields: dict[str, list[str]] = {}
    current = None
    for raw in (body or "").replace("\r\n", "\n").split("\n"):
        m = _KEY.match(raw)
        if m:
            current = m.group(1).lower()
            if current in fields:
                return {}, [f"field {current} appears twice"]
            fields[current] = [m.group(2).strip()] if m.group(2).strip() else []
            continue
        line = raw.strip()
        if current is None:
            continue
        if _SIGNED.match(raw) or line == "---" or (not line and fields[current]):
            current = None              # a signature, a rule or a blank line after content ends the field
            continue
        if line:
            fields[current].append(line[2:].strip() if line.startswith(("- ", "* ")) else line)
    problems = []
    req: dict[str, Any] = {"mode": " ".join(fields.get("mode", [])).strip().lower() or "write"}
    if req["mode"] != "write":
        problems.append(f"mode {req['mode']!r} is not handled by the loop (only file changes; research goes to the "
                        "contractor)")
    req["goal"] = " ".join(fields.get("goal", [])).strip()
    if not req["goal"]:
        problems.append("goal missing")
    paths: list[dict[str, str]] = []
    for item in fields.get("allowed_paths", []):
        found = _PATH_OP.findall(item)
        if not found:
            problems.append(f"allowed_paths item without (ADD) or (MODIFY): {item[:80]!r}")
        paths += [{"path": p, "op": op.upper()} for p, op in found]
    if not paths and not any(p.startswith("allowed_paths") for p in problems):
        problems.append("allowed_paths missing")
    req["allowed_paths"] = paths
    for key in ("acceptance", "test_commands"):
        items = [i for i in fields.get(key, []) if i]
        req[key] = items
        if not items:
            problems.append(f"{key} missing")
    return req, problems


def path_problem(path: str, op: str, policy: dict[str, Any]) -> str | None:
    """Why ``path`` may not be written by the loop, or None."""
    forb = policy["forbidden"]
    if op not in {"ADD", "MODIFY"}:
        return f"{path}: {op} is not allowed (ADD and MODIFY only)"
    if (path.startswith(("/", "./", "~")) or "\\" in path or ".." in path.split("/") or path.endswith("/")
            or not path.strip() or ":" in path):
        return f"{path}: not a plain repository file path"
    name = path.rsplit("/", 1)[-1]
    if path in forb["exact"]:
        return f"{path}: forbidden file"
    for prefix in forb["prefixes"]:
        if path.startswith(prefix):
            return f"{path}: under forbidden {prefix}"
    for glob in forb["name_globs"]:
        if fnmatch.fnmatchcase(name, glob):
            return f"{path}: forbidden file type {glob}"
    for needle in forb["substrings"]:
        if needle in path:
            return f"{path}: forbidden area ({needle})"
    if op == "MODIFY" and (fnmatch.fnmatchcase(name, "test_*.py") or fnmatch.fnmatchcase(name, "test_*.mjs")
                           or path.startswith("tests/") or "/tests/" in path):
        return f"{path}: existing tests are read-only (add a new test file instead)"
    return None


def request_problems(issue: dict[str, Any], policy: dict[str, Any]) -> tuple[dict[str, Any], list[str]]:
    """The parsed request and every reason the loop must refuse it (empty: it may start)."""
    problems = []
    if not (issue.get("title") or "").startswith(policy["title_prefix"]):
        problems.append("title prefix missing")
    if issue.get("author") not in policy["trusted_writers"]:
        problems.append(f"author {issue.get('author')!r} is not a trusted writer")
    if not _SIGNED.search(issue.get("body") or ""):
        problems.append("no AI-Agent: (or Generated by Claude Code) signature line")
    req, more = parse_request(issue.get("body") or "")
    problems += more
    seen = set()
    for p in req.get("allowed_paths", []):
        if p["path"] in seen:
            problems.append(f"{p['path']}: listed twice")
        seen.add(p["path"])
        if (why := path_problem(p["path"], p["op"], policy)) is not None:
            problems.append(why)
    if len(seen) > policy["max_files"]:
        problems.append(f"{len(seen)} files requested; at most {policy['max_files']}")
    return req, problems


def build_task(issue_number: int, req: dict[str, Any], *, base_head: str, policy: dict[str, Any]) -> dict[str, Any]:
    """The CLAUDE_CLOSED_LOOP_TASK_V1 the reviewer validates (kind code_change), from an accepted request."""
    if not _SHA40.fullmatch(base_head or ""):
        raise ValueError("base head must be a 40-hex sha")
    task_id = f"CL-{issue_number}"
    tests = list(req["test_commands"]) + [c for c in policy["full_suite"] if c not in req["test_commands"]]
    return {"profile": TASK_PROFILE, "kind": "code_change", "task_id": task_id, "loop_id": policy["loop_id"],
            "correlation_id": f"{task_id}-g1", "generation": 1,
            "max_corrective_rounds": policy["max_corrective_rounds"], "live_slot": 0,
            "expected_target_branch": policy["base_branch"], "expected_target_head": base_head,
            "work_branch": f"{policy['branch_prefix']}{issue_number}",
            "goal": req["goal"], "allowed_paths": [dict(p) for p in req["allowed_paths"]],
            "acceptance_criteria": list(req["acceptance"]) + [
                "No existing test is removed, skipped or weakened",
                f"Only the allowed paths change (ADD/MODIFY), at most {policy['max_files']} files"],
            "test_commands": tests}


def render_accept(issue_number: int, task: dict[str, Any], *, now: str) -> str:
    record = {"profile": ACCEPT_PROFILE, "issue": issue_number, "task_id": task["task_id"],
              "correlation_id": task["correlation_id"], "accepted_at": now}
    return (f"受付: Claude Loop accepted this request as task {task['task_id']} (branch `{task['work_branch']}`). "
            "The worker implements it; the reviewer checks every push; the owner merges.\n\n"
            f"{TASK_MARKER}\n{json.dumps(task, ensure_ascii=False, sort_keys=True)}\n-->\n"
            f"{ACCEPT_MARKER}\n{json.dumps(record, sort_keys=True)}\n-->\n{FOOTER}")


def render_refuse(issue_number: int, problems: list[str], *, prefix: str, now: str) -> str:
    record = {"profile": REFUSE_PROFILE, "issue": issue_number, "refused_at": now, "problems": problems}
    lines = "\n".join(f"- {p}" for p in problems)
    return (f"Claude Loop cannot take this request:\n\n{lines}\n\nFile a new `{prefix.strip()}` issue with the "
            f"fixed request; this one is not processed again.\n\n{REFUSE_MARKER}\n"
            f"{json.dumps(record, ensure_ascii=False, sort_keys=True)}\n-->\n{FOOTER}")


# ------------------------------------------------------------------------------------------------ state
class ForeignRecord(ValueError):
    """A loop record by the trusted account that was not written through a record app (a forgery or a misroute)."""


def _trusted_blocks(issue: dict[str, Any], marker: str, trusted: set[str],
                    apps: set[str] | None = None) -> list[tuple[dict[str, Any], str]]:
    """Every ``marker`` block in comments by a trusted writer.  The owner's account is shared by every AI that
    writes for the owner (Grok via Cursor, Claude, Codex), so with ``apps`` a record must also come through one of
    those GitHub Apps (``performed_via_github_app``); any other one raises ``ForeignRecord`` and the task goes to the
    owner instead of being trusted or re-done."""
    out = []
    for c in issue.get("comments") or []:
        if c.get("author") in trusted and marker in (c.get("body") or ""):
            if apps is not None and c.get("app") not in apps:
                raise ForeignRecord(f"a {marker[5:].strip()} record came through app {c.get('app')!r}")
            for obj in _block(c["body"], marker):          # a malformed block raises: never written over
                out.append((obj, c.get("created_at") or ""))
    return out


@dataclass
class TaskState:
    issue: int
    state: str
    reason: str = ""
    task: dict[str, Any] | None = None
    pr: int | None = None
    head: str | None = None
    round: int = 0
    findings: list[dict[str, Any]] = field(default_factory=list)
    accepted_at: str | None = None
    since: str | None = None
    problems: list[str] = field(default_factory=list)


def task_state(issue: dict[str, Any], pulls: list[dict[str, Any]], policy: dict[str, Any]) -> TaskState:
    """One request issue's state, derived from GitHub only (issue, trusted comments, the work branch's PR)."""
    n = issue["number"]
    trusted, apps = set(policy["trusted_writers"]), set(policy["record_apps"])
    try:
        refused = _trusted_blocks(issue, REFUSE_MARKER, trusted, apps)
        accepts = _trusted_blocks(issue, ACCEPT_MARKER, trusted, apps)
        tasks = _trusted_blocks(issue, TASK_MARKER, trusted, apps)
        receipts = _trusted_blocks(issue, RECEIPT_MARKER, trusted, apps)
    except ForeignRecord as exc:
        return TaskState(n, UNREADABLE, f"{exc}; the owner checks it, nothing is trusted or re-done")
    except (ValueError, json.JSONDecodeError):
        return TaskState(n, UNREADABLE, "a loop record on the issue is unreadable; nothing is written over it")
    if refused:
        return TaskState(n, REFUSED, "refused earlier")
    if not accepts:
        if issue.get("state") != "OPEN":
            return TaskState(n, CLOSED, "closed before it was accepted")
        req, problems = request_problems(issue, policy)
        if problems:
            return TaskState(n, INVALID, "; ".join(problems), problems=problems)
        return TaskState(n, NEW, "valid request, not accepted yet")
    if len(accepts) != 1 or len(tasks) != 1:
        return TaskState(n, UNREADABLE, f"{len(accepts)} accept records and {len(tasks)} task blocks (expected 1)")
    task, accepted_at = tasks[0][0], accepts[0][1]
    st = TaskState(n, WORKING, "accepted; the worker has not opened its PR yet", task=task, accepted_at=accepted_at,
                   since=accepted_at)
    mine = [r for r, _ in receipts if isinstance(r, dict) and r.get("correlation_id") == task.get("correlation_id")]
    if mine:
        latest = max(mine, key=lambda r: r.get("round") or 0)
        st.round, st.findings = latest.get("round") or 0, list(latest.get("findings") or [])
        if latest.get("verdict") == "PASS":
            st.state, st.reason = PASS, f"PASS at round {st.round}; waiting for the owner's merge"
            return st
        if latest.get("decision") == "TASK_BLOCKED" or latest.get("verdict") == "BLOCKED":
            st.state, st.reason = BLOCKED, f"TASK_BLOCKED at round {st.round}; the owner looks"
            return st
    branch = task.get("work_branch") or f"{policy['branch_prefix']}{n}"
    prs = [p for p in pulls if (p.get("head") or {}).get("ref") == branch]
    open_prs = [p for p in prs if p.get("state") == "open"]
    if issue.get("state") != "OPEN":
        st.state, st.reason = CLOSED, "issue closed"
        return st
    if not open_prs:
        if prs:
            st.state, st.reason = BLOCKED, f"the work PR on {branch} was closed without PASS; the owner looks"
        return st
    pr = min(open_prs, key=lambda p: p["number"])
    st.pr, st.head = pr["number"], (pr.get("head") or {}).get("sha")
    st.since = pr.get("updated_at") or accepted_at
    reviewed = [r for r in mine if r.get("pr_head_sha") == st.head]
    if not reviewed:
        st.state, st.reason = REVIEW_PENDING, f"PR #{st.pr} head {str(st.head)[:7]} has no review receipt yet"
        return st
    last = max(reviewed, key=lambda r: r.get("round") or 0)
    if last.get("decision") in {"CORRECTIVE_REQUESTED", "CORRECTIVE_EXISTS"} or last.get("verdict") == \
            "NEEDS_CORRECTION":
        st.state, st.reason = CORRECTION, f"review round {st.round} asks for corrections on PR #{st.pr}"
        st.round, st.findings = last.get("round") or st.round, list(last.get("findings") or [])
        return st
    st.state, st.reason = REVIEW_PENDING, f"PR #{st.pr} reviewed with decision {last.get('decision')!r}; waiting"
    return st


@dataclass
class Plan:
    action: str
    reason: str
    issue: int | None = None
    pr: int | None = None
    round: int | None = None
    findings: list[dict[str, Any]] = field(default_factory=list)
    refuse: list[dict[str, Any]] = field(default_factory=list)
    human_required: list[dict[str, Any]] = field(default_factory=list)
    tasks: list[dict[str, Any]] = field(default_factory=list)
    accepted_today: int = 0

    def to_json(self) -> dict[str, Any]:
        return {"action": self.action, "reason": self.reason, "issue": self.issue, "pr": self.pr,
                "round": self.round, "findings": self.findings, "refuse": self.refuse,
                "human_required": self.human_required, "tasks": self.tasks, "accepted_today": self.accepted_today}


def stop_reason(control: dict[str, Any] | None, policy: dict[str, Any], now: str) -> str | None:
    """The owner's stop switch (close the control issue or give it ``loop-stop``) and the policy's expiry."""
    if _ts(now) >= _ts(policy["expires_at"]):
        return f"the loop policy expired at {policy['expires_at']}"
    if control is None or control.get("state") == "MISSING":
        return f"control issue #{policy['control_issue']} is missing (it is the stop switch)"
    if control.get("state") != "OPEN":
        return f"control issue #{policy['control_issue']} is closed (owner stop)"
    if "loop-stop" in (control.get("labels") or []):
        return f"control issue #{policy['control_issue']} has the loop-stop label (owner stop)"
    return None


def plan(issues: list[dict[str, Any]], pulls: list[dict[str, Any]], *, control: dict[str, Any] | None,
         policy: dict[str, Any], now: str) -> Plan:
    """What the worker does on this wake: at most one START or CORRECT, plus refusals of invalid requests.

    One task is in flight at a time.  A correction of the running task comes before anything new.  New tasks are
    taken oldest first, at most ``max_new_tasks_per_day`` per UTC day (accept records count, refusals do not).
    The stop switch and the expiry stop every START and CORRECT; reviews of pushed work continue."""
    states = sorted((task_state(i, pulls, policy) for i in issues
                     if (i.get("title") or "").startswith(policy["title_prefix"])), key=lambda s: s.issue)
    out = Plan(IDLE, "no open request")
    today = now[:10]
    out.accepted_today = sum(1 for s in states if s.accepted_at and s.accepted_at[:10] == today)
    out.tasks = [{"issue": s.issue, "state": s.state, "reason": s.reason, "pr": s.pr, "round": s.round}
                 for s in states]
    stall = timedelta(minutes=policy["stall_minutes"])
    for s in states:
        if s.state in {UNREADABLE, BLOCKED}:
            out.human_required.append({"issue": s.issue, "state": s.state, "reason": s.reason})
        elif s.state in {WORKING, REVIEW_PENDING} and s.since and _ts(now) - _ts(s.since) >= stall:
            who = "worker" if s.state == WORKING else "reviewer"
            out.human_required.append({"issue": s.issue, "state": s.state,
                                       "reason": f"no progress from the {who} for {policy['stall_minutes']} minutes "
                                                 f"({s.reason})"})
    stop = stop_reason(control, policy, now)
    if stop is not None:
        out.action, out.reason = STOPPED, stop
        return out
    out.refuse = [{"issue": s.issue, "problems": s.problems} for s in states if s.state == INVALID]
    correction = [s for s in states if s.state == CORRECTION]
    if correction:
        s = correction[0]
        out.action, out.reason, out.issue, out.pr, out.round = CORRECT, s.reason, s.issue, s.pr, s.round
        out.findings = s.findings
        return out
    flying = [s for s in states if s.state in IN_FLIGHT]
    if flying:
        out.action, out.reason, out.issue, out.pr = WAIT, f"task #{flying[0].issue} in flight: {flying[0].reason}", \
            flying[0].issue, flying[0].pr
        return out
    new = [s for s in states if s.state == NEW]
    if not new:
        return out
    if out.accepted_today >= policy["max_new_tasks_per_day"]:
        out.action, out.reason = WAIT, f"daily cap reached ({out.accepted_today}/{policy['max_new_tasks_per_day']})"
        return out
    out.action, out.reason, out.issue = START, f"oldest valid request #{new[0].issue}", new[0].issue
    return out


def checkpoint_record(p: Plan, *, policy: dict[str, Any], now: str) -> dict[str, Any]:
    core = {"action": p.action, "reason": p.reason, "issue": p.issue, "pr": p.pr,
            "tasks": [t for t in p.tasks if t["state"] not in {REFUSED, CLOSED}],
            "human_required": p.human_required}
    digest = hashlib.sha256(json.dumps(core, sort_keys=True).encode()).hexdigest()[:16]
    return {"profile": CHECKPOINT_PROFILE, "loop_id": policy["loop_id"], "at": now, "digest": digest, **core}


def checkpoint_due(record: dict[str, Any], previous: dict[str, Any] | None, *, policy: dict[str, Any]) -> bool:
    if previous is None or previous.get("digest") != record["digest"]:
        return True
    try:
        return _ts(record["at"]) - _ts(previous["at"]) >= timedelta(hours=policy["heartbeat_hours"])
    except (KeyError, TypeError, ValueError):
        return True


def render_checkpoint(record: dict[str, Any]) -> str:
    human = "; ".join(f"#{h['issue']} {h['state']}" for h in record["human_required"]) or "none"
    return (f"Claude Loop checkpoint: {record['action']} ({record['reason']}). Owner needed: {human}.\n\n"
            f"{CHECKPOINT_MARKER}\n{json.dumps(record, ensure_ascii=False, sort_keys=True)}\n-->\n{FOOTER}")


# ------------------------------------------------------------------------------------------------ GitHub I/O
class GitHub:
    """Reads through ``gh api`` GETs (the Loop A reader, every page) and the loop's three comment writes."""

    def __init__(self, policy: dict[str, Any], *, get: Callable[[str], Any] | None = None,
                 post: Callable[[str, dict[str, Any]], int] | None = None):
        from .claude_jules_starter_gh import gh_get  # the hardened paging reader of the Loop A tick
        self.policy, self.repo = policy, policy["repository"]
        self.get = get or gh_get
        self.post = post or _gh_post

    def read_issue(self, n: int) -> dict[str, Any]:
        """Issue and every comment (all pages), with the GitHub App each comment came through.  A 404 on the issue
        is MISSING; any other failed read raises, never "no comments"."""
        from .claude_jules_starter_gh import NotFound
        try:
            issue = self.get(f"repos/{self.repo}/issues/{n}")
        except NotFound:
            return {"number": n, "state": "MISSING", "comments": []}
        comments = self.get(f"repos/{self.repo}/issues/{n}/comments?per_page=100")
        if not isinstance(comments, list):
            raise ValueError(f"issue #{n}: comments are not a list")
        return {"number": n, "state": "OPEN" if issue["state"] == "open" else "CLOSED", "title": issue["title"],
                "body": issue.get("body") or "", "labels": [l["name"] for l in issue.get("labels") or []],
                "author": (issue.get("user") or {}).get("login"),
                "comments": [{"id": c["id"], "author": (c.get("user") or {}).get("login"),
                              "app": (c.get("performed_via_github_app") or {}).get("slug"),
                              "body": c.get("body") or "", "created_at": c["created_at"]} for c in comments]}

    def snapshot(self) -> tuple[list[dict[str, Any]], list[dict[str, Any]], dict[str, Any]]:
        listed = self.get(f"repos/{self.repo}/issues?state=all&per_page=100")
        prefix = self.policy["title_prefix"]
        wanted = [i["number"] for i in listed if "pull_request" not in i and (i.get("title") or "").startswith(prefix)
                  and i["number"] != self.policy["control_issue"]]
        issues = [self.read_issue(n) for n in sorted(wanted)]
        pulls = [p for p in self.get(f"repos/{self.repo}/pulls?state=all&per_page=100")
                 if str((p.get("head") or {}).get("ref", "")).startswith(self.policy["branch_prefix"])]
        return issues, pulls, self.read_issue(self.policy["control_issue"])

    def base_head(self) -> str:
        return self.get(f"repos/{self.repo}/commits/{self.policy['base_branch']}")["sha"]

    def comment(self, n: int, body: str) -> int:
        return self.post(f"repos/{self.repo}/issues/{n}/comments", {"body": body})


def _gh_post(path: str, payload: dict[str, Any]) -> int:
    proc = subprocess.run(["gh", "api", "--method", "POST", path, "--input", "-"], input=json.dumps(payload),
                          capture_output=True, text=True, encoding="utf-8", timeout=60)
    return proc.returncode


def _now() -> str:
    return _fmt(datetime.now(timezone.utc))


EXIT_OK, EXIT_REFUSED, EXIT_UNKNOWN = 0, 2, 4


def cmd_next(gh: GitHub, *, now: str) -> tuple[int, dict[str, Any]]:
    issues, pulls, control = gh.snapshot()
    return EXIT_OK, plan(issues, pulls, control=control, policy=gh.policy, now=now).to_json()


def cmd_accept(gh: GitHub, n: int, *, now: str) -> tuple[int, dict[str, Any]]:
    """Record the task for request #n, only when a fresh plan says START #n.  Exactly one accept, ever."""
    issues, pulls, control = gh.snapshot()
    p = plan(issues, pulls, control=control, policy=gh.policy, now=now)
    if p.action != START or p.issue != n:
        return EXIT_REFUSED, {"result": "REFUSED", "reason": f"plan is {p.action} #{p.issue} ({p.reason})"}
    issue = next(i for i in issues if i["number"] == n)
    req, problems = request_problems(issue, gh.policy)
    if problems:                                           # the plan said NEW, so this is a race: never accept
        return EXIT_REFUSED, {"result": "REFUSED", "reason": "; ".join(problems)}
    task = build_task(n, req, base_head=gh.base_head(), policy=gh.policy)
    code = gh.comment(n, render_accept(n, task, now=now))
    try:
        after = task_state(gh.read_issue(n), pulls, gh.policy)      # readback, never a resend
    except Exception as exc:                                         # noqa: BLE001 - the write may have landed
        return EXIT_UNKNOWN, {"result": "UNKNOWN", "reason": f"post exit {code}; readback failed ({exc}); the next "
                                                             "wake reads it back, never re-sent"}
    if after.state in {WORKING, REVIEW_PENDING} and after.task == task:
        return EXIT_OK, {"result": "ACCEPTED", "task": task}
    return EXIT_UNKNOWN, {"result": "UNKNOWN", "reason": f"post exit {code}; readback state {after.state}; the next "
                                                         "wake reads it back, never re-sent"}


def cmd_refuse(gh: GitHub, n: int, *, now: str) -> tuple[int, dict[str, Any]]:
    issue = gh.read_issue(n)
    st = task_state(issue, [], gh.policy)
    if st.state != INVALID:
        return EXIT_REFUSED, {"result": "REFUSED", "reason": f"#{n} is {st.state}, not INVALID"}
    code = gh.comment(n, render_refuse(n, st.problems, prefix=gh.policy["title_prefix"], now=now))
    try:
        refused = task_state(gh.read_issue(n), [], gh.policy).state == REFUSED
    except Exception:                                                # noqa: BLE001 - the write may have landed
        refused = False
    if refused:
        return EXIT_OK, {"result": "REFUSAL_POSTED", "problems": st.problems}
    return EXIT_UNKNOWN, {"result": "UNKNOWN", "reason": f"post exit {code}; read back on the next wake"}


def cmd_show(gh: GitHub, n: int) -> tuple[int, dict[str, Any]]:
    """The records the reviewer may trust for request #n: its state, the task block and the receipts (read-only)."""
    issue = gh.read_issue(n)
    pulls = gh.snapshot()[1]
    st = task_state(issue, pulls, gh.policy)
    trusted, apps = set(gh.policy["trusted_writers"]), set(gh.policy["record_apps"])
    receipts: list[Any] = []
    if st.state != UNREADABLE:
        receipts = [r for r, _ in _trusted_blocks(issue, RECEIPT_MARKER, trusted, apps)
                    if isinstance(r, dict) and st.task and r.get("correlation_id") == st.task.get("correlation_id")]
    return EXIT_OK, {"issue": n, "state": st.state, "reason": st.reason, "task": st.task, "pr": st.pr,
                     "head": st.head, "round": st.round, "receipts": receipts}


def cmd_checkpoint(gh: GitHub, *, now: str) -> tuple[int, dict[str, Any]]:
    issues, pulls, control = gh.snapshot()
    p = plan(issues, pulls, control=control, policy=gh.policy, now=now)
    record = checkpoint_record(p, policy=gh.policy, now=now)
    trusted, apps = set(gh.policy["trusted_writers"]), set(gh.policy["record_apps"])
    try:
        previous = [r for r, _ in _trusted_blocks(control or {}, CHECKPOINT_MARKER, trusted, apps)]
    except (ValueError, json.JSONDecodeError):
        return EXIT_REFUSED, {"result": "REFUSED", "reason": "a checkpoint on the control issue is unreadable"}
    if (control or {}).get("state") != "OPEN" or not checkpoint_due(record, previous[-1] if previous else None,
                                                                     policy=gh.policy):
        return EXIT_OK, {"result": "NOT_DUE", "checkpoint": record}
    code = gh.comment(gh.policy["control_issue"], render_checkpoint(record))
    return (EXIT_OK if code == 0 else EXIT_UNKNOWN), {"result": "WRITTEN" if code == 0 else "UNKNOWN",
                                                      "checkpoint": record}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="claude_only_loop", description=__doc__.split("\n")[0])
    ap.add_argument("command", choices=["next", "accept", "refuse", "show", "checkpoint"])
    ap.add_argument("--policy", required=True)
    ap.add_argument("--issue", type=int)
    ap.add_argument("--out")
    args = ap.parse_args(argv)
    with open(args.policy, encoding="utf-8") as fh:
        policy = load_policy(json.load(fh))
    gh = GitHub(policy)
    now = _now()
    if args.command in {"accept", "refuse", "show"} and args.issue is None:
        ap.error("--issue is required")
    try:
        code, report = {"next": lambda: cmd_next(gh, now=now),
                        "accept": lambda: cmd_accept(gh, args.issue, now=now),
                        "refuse": lambda: cmd_refuse(gh, args.issue, now=now),
                        "show": lambda: cmd_show(gh, args.issue),
                        "checkpoint": lambda: cmd_checkpoint(gh, now=now)}[args.command]()
    except Exception as exc:                                  # noqa: BLE001 - a read failed: nothing was written
        code, report = EXIT_UNKNOWN, {"result": "READ_FAILED", "reason": f"{type(exc).__name__}: {exc}"}
    text = json.dumps(report, ensure_ascii=False, indent=2, sort_keys=True)
    if args.out:
        with open(args.out, "w", encoding="utf-8") as fh:
            fh.write(text + "\n")
    print(text)
    return code


if __name__ == "__main__":
    sys.exit(main())
