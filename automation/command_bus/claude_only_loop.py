"""Claude-only loop ("Claude Loop", lane ``claude-claude-auto``): the queue rules as deterministic code.

The Claude x Jules loop (prod-c1) ended on 2026-10-30 (owner decision; Jules is read-only from 2026-11-11).  This
loop keeps its proven parts and drops Jules:

* the work queue is GitHub Issues titled ``[claude loop] ...`` holding a plain request block (the same fields as the
  contractor routine: ``goal``, ``allowed_paths``, ``acceptance``, ``test_commands``, plus an ``AI-Agent:`` line);
* a worker Routine (the former takeover worker) wakes on ``issues.opened`` and on its recovery schedule, asks this
  module what to do (``next``), records the accepted task (``accept``), implements it on ``claude/loop-<issue>`` and
  opens a PR ``Fixes #<issue>``;
* the reviewer Routine (the former closed-loop reviewer) reviews every head of that PR with the unchanged
  ``claude-closed-loop-receipt v1`` receipts; NEEDS_CORRECTION sends the task back to the worker, up to
  ``max_corrective_rounds``; anything left after that is TASK_BLOCKED for the owner;
* PASS PRs wait for the owner's merge.  Nothing here merges, labels, or changes settings.

GitHub is the only state.  A fresh process reading the same issues, comments and PRs takes the same decision, and
every write is guarded by a marker that a re-run finds, so a crash or a duplicate wake never starts work twice.  An
unknown write outcome is read back on the next wake, never resent.

    python3 -m automation.command_bus.claude_only_loop next --policy docs/claude-loop/active/policy.json --out next.json
    python3 -m automation.command_bus.claude_only_loop accept --policy ... --issue 501
    python3 -m automation.command_bus.claude_only_loop refuse --policy ... --issue 502
    python3 -m automation.command_bus.claude_only_loop show --policy ... --issue 501
    python3 -m automation.command_bus.claude_only_loop checkpoint --policy ...
"""
