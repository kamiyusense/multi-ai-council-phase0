"""STATIC checks of V4 board input (step S5): proposals, approvals and resume commands on the board Issue."""
from __future__ import annotations

import json
import unittest

from automation.command_bus import v4_board_input as vi
from automation.command_bus.approval_comment import judge_owner_command, load_policy

POLICY = load_policy()
OWNER = 20355232
PHRASES = {"続けて OK claude": "claude", "続けて OK codex": "codex", "続けて OK grok": "grok"}
APPROVAL_WORD = POLICY.approval_word


def owner(cid, body, at, *, edited=None, app=None, user=OWNER):
    return {"id": cid, "user": {"id": user}, "body": body, "created_at": at, "updated_at": edited or at,
            "performed_via_github_app": app}


def proposal(cid, pid, at, *, edited=None, summary="S5 のテスト提案"):
    body = (f"提案です。\n\n{vi.PROPOSAL_MARKER} {json.dumps({'proposal_id': pid, 'summary_ja': summary})} -->\n\n"
            "Generated by Claude Code")
    return owner(cid, body, at, edited=edited, app={"slug": "claude"})


def fold(comments, record=None):
    return vi.fold_comments(record or vi.empty_record(462), comments, resume_phrases=PHRASES, policy=POLICY)


class ApprovalTests(unittest.TestCase):
    def test_approval_after_one_pending_proposal_is_applied_once(self):
        out = fold([proposal(1, "p-one", "2026-10-24T01:00:00Z"), owner(2, APPROVAL_WORD, "2026-10-24T02:00:00Z")])
        self.assertEqual(out["proposals"]["p-one"]["state"], "APPROVED")
        self.assertEqual(out["proposals"]["p-one"]["approved_by_comment"], 2)
        self.assertEqual(out["used_comment_ids"], [2])
        again = fold([proposal(1, "p-one", "2026-10-24T01:00:00Z"), owner(2, APPROVAL_WORD, "2026-10-24T02:00:00Z")], out)
        self.assertEqual(again, out)

    def test_approval_does_not_attach_to_a_later_proposal(self):
        out = fold([owner(2, APPROVAL_WORD, "2026-10-24T01:00:00Z"), proposal(3, "p-two", "2026-10-24T02:00:00Z")])
        self.assertEqual(out["proposals"]["p-two"]["state"], "PENDING")
        self.assertEqual(out["rejected"][-1]["reason"], "NO_PENDING_PROPOSAL")
        self.assertEqual(out["used_comment_ids"], [2])

    def test_two_pending_proposals_make_the_approval_ambiguous(self):
        out = fold([proposal(1, "p-a", "2026-10-24T01:00:00Z"), proposal(2, "p-b", "2026-10-24T01:10:00Z"),
                    owner(3, APPROVAL_WORD, "2026-10-24T02:00:00Z")])
        self.assertEqual({p["state"] for p in out["proposals"].values()}, {"PENDING"})
        self.assertEqual(out["rejected"][-1]["reason"], "AMBIGUOUS")

    def test_non_approvals_are_refused(self):
        cases = {"VIA_APP": owner(2, APPROVAL_WORD, "2026-10-24T02:00:00Z", app={"slug": "cursor"}),
                 "EDITED": owner(2, APPROVAL_WORD, "2026-10-24T02:00:00Z", edited="2026-10-24T02:05:00Z")}
        for reason, comment in cases.items():
            out = fold([proposal(1, "p-one", "2026-10-24T01:00:00Z"), comment])
            self.assertEqual(out["proposals"]["p-one"]["state"], "PENDING", reason)
            self.assertEqual(out["rejected"][-1]["reason"], reason)
        for comment in (owner(2, APPROVAL_WORD, "2026-10-24T02:00:00Z", user=1),
                        owner(2, f"{APPROVAL_WORD}\n\nAI-Agent: grok", "2026-10-24T02:00:00Z"),
                        owner(2, f"{APPROVAL_WORD}します", "2026-10-24T02:00:00Z")):
            out = fold([proposal(1, "p-one", "2026-10-24T01:00:00Z"), comment])
            self.assertEqual(out["proposals"]["p-one"]["state"], "PENDING")
            self.assertEqual(out["used_comment_ids"], [])

    def test_proposal_edited_before_the_approval_is_fine_after_is_not(self):
        out = fold([proposal(1, "p-one", "2026-10-24T01:00:00Z", edited="2026-10-24T01:30:00Z"),
                    owner(2, APPROVAL_WORD, "2026-10-24T02:00:00Z")])
        self.assertEqual(out["proposals"]["p-one"]["state"], "APPROVED")
        later = fold([proposal(1, "p-one", "2026-10-24T01:00:00Z", edited="2026-10-24T03:00:00Z"),
                      owner(2, APPROVAL_WORD, "2026-10-24T02:00:00Z")], out)
        self.assertEqual(later["proposals"]["p-one"]["state"], "CHANGED_AFTER_APPROVAL")

    def test_unsigned_or_malformed_proposals_are_ignored(self):
        unsigned = proposal(1, "p-one", "2026-10-24T01:00:00Z")
        unsigned["body"] = unsigned["body"].replace("Generated by Claude Code", "")
        bad_id = proposal(2, "P ONE", "2026-10-24T01:00:00Z")
        self.assertEqual(fold([unsigned, bad_id])["proposals"], {})


class ResumeTests(unittest.TestCase):
    def test_latest_resume_per_ai_is_kept(self):
        out = fold([owner(1, "続けて OK claude", "2026-10-24T01:00:00Z"), owner(2, "続けて OK claude。", "2026-10-24T02:00:00Z"),
                    owner(3, "続けて OK grok", "2026-10-24T02:30:00Z")])
        self.assertEqual(out["resume"], {"claude": {"comment_id": 2, "at": "2026-10-24T02:00:00Z"},
                                         "grok": {"comment_id": 3, "at": "2026-10-24T02:30:00Z"}})

    def test_resume_written_through_an_app_is_refused(self):
        out = fold([owner(1, "続けて OK codex", "2026-10-24T01:00:00Z", app={"slug": "cursor"})])
        self.assertEqual(out["resume"], {})
        self.assertEqual(out["rejected"][-1]["reason"], "VIA_APP")

    def test_other_owner_chatter_is_ignored_and_not_consumed(self):
        out = fold([owner(1, "続けて", "2026-10-24T01:00:00Z"), owner(2, "続けて OK antigravity", "2026-10-24T01:00:00Z")])
        self.assertEqual((out["resume"], out["used_comment_ids"], out["rejected"]), ({}, [], []))

    def test_command_judge_never_treats_the_approval_word_as_a_command(self):
        ok, reason, _ = judge_owner_command(owner(1, APPROVAL_WORD, "2026-10-24T01:00:00Z"),
                                            phrases=[APPROVAL_WORD], used_comment_ids=[], policy=POLICY)
        self.assertEqual((ok, reason), (False, "NOT_COMMAND"))


class RecordTests(unittest.TestCase):
    def test_record_shape_is_validated(self):
        self.assertEqual(vi.validate_record(vi.empty_record(462), 462), vi.empty_record(462))
        for bad in ({}, {**vi.empty_record(462), "extra": 1}, vi.empty_record(1)):
            with self.assertRaises(vi.InputError):
                vi.validate_record(bad, 462)

    def test_rejected_list_is_bounded(self):
        comments = [owner(i, "続けて OK codex", f"2026-10-24T01:{i:02d}:00Z", app={"slug": "x"}) for i in range(30)]
        self.assertEqual(len(fold(comments)["rejected"]), 20)


if __name__ == "__main__":
    unittest.main()
