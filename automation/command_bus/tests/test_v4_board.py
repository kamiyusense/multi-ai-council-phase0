def checkpoint(at, outcome="MERGE_WAIT", digest="d1", user=OWNER, isolated=(), task="prod-c1-aaa"):
    record = {"outcome": outcome, "state_digest": digest, "isolated": list(isolated),
              "human_actions": [{"action": "merge", "prs_of_tasks": [task], "unblocks": None}]}
    body = f"Loop checkpoint: {outcome}.\n\n{CHECKPOINT_MARKER}\n{json.dumps(record)}\n-->\n"
    return {"user": {"id": user}, "created_at": at.isoformat().replace("+00:00", "Z"), "body": body}


def board_body(inner="old"):
    return f"header\n\n{v4_board.BOARD_START}\n{inner}\n{v4_board.BOARD_END}\n\nGenerated by Claude Code\n"


class FakeGitHub:
    def __init__(self, comments, board, board_comments=(), record=None):
        self.comments, self.board, self.board_comments, self.calls = comments, board, list(board_comments), []
        self.branch = record is not None
        self.record = record

    def __call__(self, method, path, payload):
        self.calls.append((method, path))
        if method == "GET" and "/comments?" in path:
            page = int(path.rsplit("page=", 1)[1])
            source = self.board_comments if f"/issues/{CONFIG.board_issue}/" in path else self.comments
            return source[(page - 1) * 100:page * 100]
        if method == "GET" and "/branches/" in path:
            if not self.branch:
                raise cli.NotFound(path)
            return {"name": CONFIG.record_branch}
        if method == "GET" and "/contents/" in path:
            if self.record is None:
                raise cli.NotFound(path)
            text = json.dumps(self.record).encode("utf-8")
            return {"encoding": "base64", "sha": "s1", "content": base64.b64encode(text).decode("ascii")}
        if method == "GET" and "/git/ref/heads/main" in path:
            return {"object": {"sha": "m1"}}
        if method == "POST" and path.endswith("/git/refs"):
            self.branch = True
            return {}
        if method == "PUT" and "/contents/" in path:
            self.record = json.loads(base64.b64decode(payload["content"]).decode("utf-8"))
            self.put_payload = payload
            return {}
        if method == "GET":
            return self.board
        if method == "PATCH":
            self.board = {**self.board, "body": payload["body"]}
            return self.board
        raise AssertionError(method)


class RenderTests(unittest.TestCase):
    def render(self, comments):
        return v4_board.render_board(LANES, v4_board.checkpoints_from_comments(comments, OWNER), now=NOW, config=CONFIG)

    def test_all_lanes_listed_and_signed_and_no_bare_approval(self):
        text = self.render([checkpoint(NOW - timedelta(hours=1))])
        for lane in LANES:
            self.assertIn(lane["display_name_ja"], text)
        self.assertIn("AI-Agent: claude", text)
        self.assertFalse(any(is_bare_approval(line, load_policy()) for line in text.splitlines()))
        self.assertTrue(text.startswith(v4_board.BOARD_START) and text.endswith(v4_board.BOARD_END))

    def test_quiet_loop_has_no_alerts(self):
        text = self.render([checkpoint(NOW - timedelta(hours=2), outcome="CONTINUE")])
        self.assertIn("🟢 今はなし", text)
        self.assertIn("作業中", text)

    def test_stale_checkpoint_is_flagged(self):
        text = self.render([checkpoint(NOW - timedelta(hours=10), outcome="CONTINUE")])
        self.assertIn("見回りが止まってるかも", text)

    def test_long_merge_wait_counts_from_the_first_checkpoint_with_the_same_digest(self):
        comments = [checkpoint(NOW - timedelta(hours=40), digest="old"),
                    checkpoint(NOW - timedelta(hours=30)), checkpoint(NOW - timedelta(hours=1))]
        text = self.render(comments)
        self.assertIn("マージ待ち：30時間", text)
        self.assertIn("マージ待ちが 30時間 続いてる", text)
        self.assertIn("prod-c1-aaa", text)

    def test_short_merge_wait_is_shown_but_not_flagged(self):
        text = self.render([checkpoint(NOW - timedelta(hours=2))])
        self.assertIn("マージ待ち：2時間", text)
        self.assertIn("🟢 今はなし", text)

    def test_human_required_tasks_are_flagged(self):
        isolated = [{"task_id": "prod-c1-bbb", "human_required": True}, {"task_id": "prod-c1-ccc", "human_required": False}]
        text = self.render([checkpoint(NOW - timedelta(hours=1), outcome="CONTINUE", isolated=isolated)])
        self.assertIn("相棒の判断が必要なタスク：prod-c1-bbb", text)
        self.assertNotIn("prod-c1-ccc", text)

    def test_only_the_owner_account_counts_and_missing_records_are_unknown(self):
        text = self.render([checkpoint(NOW - timedelta(hours=1), user=1)])
        self.assertIn("UNKNOWN", text)
        self.assertIn("記録が見つからない", text)

    def test_malformed_owner_checkpoint_fails_closed(self):
        bad = {"user": {"id": OWNER}, "created_at": "2026-10-24T00:00:00Z", "body": f"{CHECKPOINT_MARKER}\nnot json\n-->"}
        with self.assertRaises(v4_board.BoardError):
            v4_board.checkpoints_from_comments([bad], OWNER)


class BlockTests(unittest.TestCase):
    def test_text_outside_the_markers_is_kept(self):
        out = v4_board.replace_board_block(board_body(), f"{v4_board.BOARD_START}\nnew\n{v4_board.BOARD_END}")
        self.assertTrue(out.startswith("header\n\n"))
        self.assertTrue(out.endswith("Generated by Claude Code\n"))
        self.assertIn("\nnew\n", out)
        self.assertNotIn("old", out)

    def test_missing_or_doubled_markers_fail_closed(self):
        for body in ("no markers", board_body() + v4_board.BOARD_START, f"{v4_board.BOARD_END}{v4_board.BOARD_START}"):
            with self.assertRaises(v4_board.BoardError):
                v4_board.replace_board_block(body, "x")


class CliTests(unittest.TestCase):
    def test_writes_once_then_is_unchanged(self):
        gh = FakeGitHub([checkpoint(NOW - timedelta(hours=1))], {"state": "open", "body": board_body()})
        self.assertEqual(cli.run(gh, REPO, NOW), "UPDATED")
        self.assertEqual([c for c in gh.calls if c[0] == "PATCH"], [("PATCH", f"repos/{REPO}/issues/{CONFIG.board_issue}")])
        self.assertEqual(cli.run(gh, REPO, NOW), "UNCHANGED")
        self.assertEqual(sum(1 for c in gh.calls if c[0] == "PATCH"), 1)

    def test_reads_every_comment_page(self):
        filler = [{"user": {"id": 1}, "created_at": "2026-10-01T00:00:00Z", "body": "x"}] * 150
        gh = FakeGitHub(filler + [checkpoint(NOW - timedelta(hours=1))], {"state": "open", "body": board_body()})
        cli.run(gh, REPO, NOW)
        self.assertIn("人のマージ待ち", gh.board["body"])

    def test_fail_closed_cases_never_write(self):
        cases = [(REPO, {"state": "closed", "body": board_body()}), (REPO, {"state": "open", "body": "no markers"}),
                 ("someone/else", {"state": "open", "body": board_body()}),
                 (REPO, {"state": "open", "body": board_body(), "pull_request": {}})]
        for repo, board in cases:
            gh = FakeGitHub([checkpoint(NOW - timedelta(hours=1))], board)
            with self.assertRaises(v4_board.BoardError):
                cli.run(gh, repo, NOW)
            self.assertFalse(any(c[0] == "PATCH" for c in gh.calls))

    def test_owner_resume_comment_is_recorded_on_the_record_branch_before_the_board(self):
        resume = {"id": 77, "user": {"id": OWNER}, "body": "続けて OK codex", "created_at": "2026-10-24T04:00:00Z",
                  "updated_at": "2026-10-24T04:00:00Z", "performed_via_github_app": None}
        gh = FakeGitHub([checkpoint(NOW - timedelta(hours=1))], {"state": "open", "body": board_body()}, [resume])
        self.assertEqual(cli.run(gh, REPO, NOW), "UPDATED")
        writes = [c for c in gh.calls if c[0] in ("POST", "PUT", "PATCH")]
        self.assertEqual([c[0] for c in writes], ["POST", "PUT", "PATCH"])
        self.assertEqual(gh.record["resume"], {"codex": {"comment_id": 77, "at": "2026-10-24T04:00:00Z"}})
        self.assertEqual(gh.put_payload["branch"], "v4-board-record")
        self.assertIn("AI-Agent: claude", gh.put_payload["message"])
        self.assertIn("codex：「続けて OK」を受け取った", gh.board["body"])
        before = len(gh.calls)
        cli.run(gh, REPO, NOW)
        self.assertFalse(any(c[0] in ("POST", "PUT") for c in gh.calls[before:]))

    def test_malformed_record_fails_closed_without_writes(self):
        gh = FakeGitHub([], {"state": "open", "body": board_body()}, record={"schema_version": 2})
        with self.assertRaises(v4_board.BoardError):
            cli.run(gh, REPO, NOW)
        self.assertFalse(any(c[0] in ("POST", "PUT", "PATCH") for c in gh.calls))

    def test_dry_run_never_writes(self):
        gh = FakeGitHub([], {"state": "open", "body": board_body()})
        with unittest.mock.patch("builtins.print"):
            self.assertEqual(cli.run(gh, REPO, NOW, dry_run=True), "DRY_RUN")
        self.assertFalse(any(c[0] == "PATCH" for c in gh.calls))


