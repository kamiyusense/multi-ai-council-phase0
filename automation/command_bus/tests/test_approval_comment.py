"""Signature rule and human approval comments (docs/RELAY_TOWER_DIRECTION_V4.md section 2)."""
from __future__ import annotations

import json
import tempfile
import unittest
from pathlib import Path

from automation.command_bus import approval_comment as ac

POLICY = ac.load_policy()
OWNER = 20355232
CHANGED = "2026-10-23T01:00:00Z"


def comment(body="承認", user_id=OWNER, created="2026-10-23T02:00:00Z", updated=None, cid=101):
    return {"id": cid, "user": {"id": user_id, "login": "kamiyusense"}, "body": body,
            "created_at": created, "updated_at": updated or created, "performed_via_github_app": None}


def judge(c, changed=CHANGED, used=()):
    return ac.judge_approval(c, target_last_changed_at=changed, used_comment_ids=used, policy=POLICY)


class TestPolicy(unittest.TestCase):
    def test_repository_policy(self):
        self.assertEqual(POLICY.owner_user_id, OWNER)
        self.assertEqual(POLICY.approval_word, "承認")
        self.assertEqual(set(POLICY.agents), {"claude", "grok", "codex", "antigravity"})
        for marker in ("Generated by Claude Code", "Generated with [Claude Code]", "AI-Agent:"):
            self.assertIn(marker, POLICY.markers)

    def test_malformed_policy_fails(self):
        good = json.loads(ac.DEFAULT_POLICY_PATH.read_text(encoding="utf-8"))
        for change in ({"schema_version": 2}, {"owner_user_id": True}, {"owner_user_id": 0}, {"approval_word": " "},
                       {"signatures": []}, {"signatures": [{"marker": ""}]}, {"agents": []}):
            with self.subTest(change=change), tempfile.TemporaryDirectory() as tmp:
                path = Path(tmp) / "p.json"
                path.write_text(json.dumps({**good, **change}), encoding="utf-8")
                with self.assertRaises(ValueError):
                    ac.load_policy(path)


class TestBareApproval(unittest.TestCase):
    def test_accepted_forms(self):
        for body in ("承認", " 承認 ", "承認\n", "\r\n承認\r\n", "承認。", "　承認　", "承認 。"):
            with self.subTest(body=body):
                self.assertTrue(ac.is_bare_approval(body, POLICY))

    def test_rejected_forms(self):
        for body in ("承認します", "OK", "承認待ち", "承認。。", "「承認」", "承認\nありがとう", "", "承 認"):
            with self.subTest(body=body):
                self.assertFalse(ac.is_bare_approval(body, POLICY))


class TestJudgeApproval(unittest.TestCase):
    def test_owner_bare_unsigned_unedited_after_change_is_approval(self):
        self.assertEqual(judge(comment()), (True, "APPROVED"))

    def test_rejections(self):
        cases = {
            "NOT_OWNER": comment(user_id=41898282),
            "NOT_BARE_APPROVAL": comment(body="承認します"),
            "EDITED": comment(updated="2026-10-23T02:05:00Z"),
            "BEFORE_TARGET_CHANGE": comment(created="2026-10-23T00:59:59Z"),
            "TIME_UNKNOWN": comment(created="yesterday"),
        }
        for reason, c in cases.items():
            with self.subTest(reason=reason):
                self.assertEqual(judge(c), (False, reason))

    def test_same_second_as_change_is_not_after(self):
        self.assertEqual(judge(comment(created=CHANGED)), (False, "BEFORE_TARGET_CHANGE"))

    def test_signed_body_is_never_an_approval(self):
        for body in ("承認\nAI-Agent: grok", "承認\n_Generated by Claude Code_"):
            with self.subTest(body=body):
                self.assertFalse(judge(comment(body=body))[0])

    def test_written_through_an_app_is_never_an_approval(self):
        for slug in ("claude", "cursor"):
            with self.subTest(app=slug):
                c = {**comment(), "performed_via_github_app": {"slug": slug}}
                self.assertEqual(judge(c), (False, "VIA_APP"))
        c = comment()
        del c["performed_via_github_app"]
        self.assertEqual(judge(c), (False, "APP_UNKNOWN"))

    def test_observed_issue_459_comments(self):
        # Shapes read back from #459 on 2026-10-23 (owner via GitHub Mobile + a 👍; Grok Bot via Cursor).
        owner = {"id": 6364045450, "user": {"id": OWNER}, "body": "承認", "created_at": "2026-10-23T11:40:49Z",
                 "updated_at": "2026-10-23T11:40:49Z", "performed_via_github_app": None}
        grok = {"id": 6364058115, "user": {"id": OWNER}, "body": "署名ルールの試しコメントです。\nAI-Agent: grok",
                "created_at": "2026-10-23T11:41:35Z", "updated_at": "2026-10-23T11:41:35Z",
                "performed_via_github_app": {"slug": "cursor", "name": "Cursor"}}
        changed = "2026-10-23T08:00:00Z"
        self.assertEqual(judge(owner, changed=changed), (True, "APPROVED"))
        self.assertEqual(judge(grok, changed=changed), (False, "NOT_BARE_APPROVAL"))
        self.assertEqual(judge({**grok, "body": "承認"}, changed=changed), (False, "VIA_APP"))

    def test_used_once(self):
        self.assertEqual(judge(comment(cid=7), used=[7]), (False, "ALREADY_USED"))

    def test_fail_closed_on_missing_fields(self):
        self.assertEqual(judge({"body": "承認"}), (False, "NOT_OWNER"))
        self.assertEqual(judge(comment(user_id=True)), (False, "NOT_OWNER"))
        self.assertEqual(judge(comment(), changed=""), (False, "TARGET_TIME_UNKNOWN"))
        self.assertEqual(judge(comment(created="2026-10-23T02:00:00")), (False, "TIME_UNKNOWN"))
        self.assertEqual(judge(comment(cid=None)), (False, "ID_UNKNOWN"))


class TestCheckAiWrite(unittest.TestCase):
    def test_signed_body_passes(self):
        body = "承認待ちの提案です。\n\nAI-Agent: grok"
        self.assertEqual(ac.check_ai_write(body, POLICY), body)

    def test_refusals(self):
        for body in ("", "署名なしの本文", "承認\nAI-Agent: grok", "説明\n承認。\n\n_Generated by Claude Code_"):
            with self.subTest(body=body):
                with self.assertRaises(ac.AiWriteRefused):
                    ac.check_ai_write(body, POLICY)


